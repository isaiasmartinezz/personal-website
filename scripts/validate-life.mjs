// `npm run validate:life` — also runs as `prebuild`, so a bad content file fails
// the build with a message that names the file and the field.
import { validateLife } from "../schema/validate.mjs";

const result = validateLife({ root: process.cwd() });

if (!result.ok) {
  console.error(`\n✗ content/life validation failed (${result.errors.length} problem${result.errors.length === 1 ? "" : "s"}):\n`);
  for (const error of result.errors) console.error(`  - ${error}`);
  console.error("\ncontent/life/ is generated by the Publisher; fix the source in the dashboard and re-export.\n");
  process.exit(1);
}

const byTier = result.items.reduce((acc, { tier }) => ({ ...acc, [tier]: (acc[tier] ?? 0) + 1 }), {});
console.log(`✓ content/life: ${result.items.length} items valid (${Object.entries(byTier).map(([t, n]) => `${n} ${t}`).join(", ") || "none"})`);
